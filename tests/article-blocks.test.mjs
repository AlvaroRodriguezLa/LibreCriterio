import assert from 'node:assert/strict';
import {createMarkdownProcessor} from '@astrojs/markdown-remark';
import {demoArticle} from '../src/lib/article-blocks/demo.mjs';
import remark from '../src/lib/article-blocks/remark-plugin.mjs';
import {validateArticleBlocks,renderArticleBlock,stripArticleBlocks,decodeArticleBlock} from '../public/article-blocks.mjs';
const blocks=validateArticleBlocks(demoArticle.text);
assert.deepEqual(blocks.map(b=>b.block.type),['concept-flow','editorial-callout']);
const processor=await createMarkdownProcessor({remarkPlugins:[remark]});
const html=(await processor.render(demoArticle.text)).code;
assert.match(html,/class="concept-flow"/);assert.match(html,/La puerta de salida/);assert.doesNotMatch(html,/language-oneshot/);
assert.doesNotMatch(stripArticleBlocks(demoArticle.text),/"steps"/);
const injected=renderArticleBlock({type:'concept-flow',title:'<script>alert(1)</script>',steps:[{title:'<img src=x onerror=alert(1)>',text:'<a>mal</a>'},{title:'Segundo',text:'Seguro'}]});
assert.doesNotMatch(injected,/<script>|<img|<[^>]+\sonerror=/);assert.match(injected,/&lt;script&gt;/);
assert.throws(()=>renderArticleBlock({type:'concept-flow',title:'Uno',steps:[{title:'Solo'}]}),/entre 2 y 6/);
assert.throws(()=>renderArticleBlock({type:'source-note',url:'javascript:alert(1)'}),/https/);
assert.throws(()=>renderArticleBlock({type:'source-note',url:'https://user:pass@example.org'}),/credenciales/);
assert.throws(()=>decodeArticleBlock('{bad'),/JSON no válido/);
assert.throws(()=>validateArticleBlocks('```oneshot\n{"type":"editorial-callout","text":"abierto"}'),/falta cerrar/);
console.log('Bloques: renderizado Astro, validación y escape correctos');
